/**
 * Switch Application Language ('mr' | 'en')
 */
function setLanguage(lang) {
  if (typeof document === 'undefined') return;
  if (lang !== 'en' && lang !== 'mr') lang = 'mr';
  try {
    if (typeof localStorage !== 'undefined') localStorage.setItem('mcc_lang', lang);
  } catch (e) { }

  document.documentElement.lang = lang;
  document.documentElement.setAttribute('data-lang', lang);
  if (document.body) {
    document.body.setAttribute('data-lang', lang);
  }

  document.querySelectorAll('.lang-btn').forEach(btn => {
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  const langData = translations[lang];

  // Strict toggle support for server-rendered dynamic content. Elements may carry
  // data-mr/data-en values and are updated immediately without a page refresh.
  document.querySelectorAll('[data-mr][data-en]').forEach(el => {
    const value = el.getAttribute(lang === 'mr' ? 'data-mr' : 'data-en');
    if (value !== null) el.textContent = value;
  });

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (langData && langData[key] !== undefined) {
      const textVal = langData[key];
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = textVal;
      } else {
        const icon = el.querySelector('i, svg');
        if (icon) {
          el.innerHTML = icon.outerHTML + ' ' + textVal;
        } else {
          el.textContent = textVal;
        }
      }
    }
  });

  // Notify active listeners (such as timeline showcase card update)
  window.dispatchEvent(new CustomEvent('mccLanguageChanged', { detail: { lang } }));
}

// Immediate execution & fast DOM listener
(function initMccI18n() {
  if (typeof document === 'undefined') return;
  const savedLang = (typeof localStorage !== 'undefined' && localStorage.getItem('mcc_lang')) || 'mr';

  // Set attribute on html element immediately
  document.documentElement.lang = savedLang;
  document.documentElement.setAttribute('data-lang', savedLang);

  const applyEarly = () => {
    setLanguage(savedLang);
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.onclick = (e) => {
        e.preventDefault();
        const l = btn.getAttribute('data-lang');
        document.cookie = "mcc_lang=" + l + "; path=/; max-age=31536000; SameSite=Lax";
        try {
          if (typeof localStorage !== 'undefined') localStorage.setItem('mcc_lang', l);
        } catch (err) {}
        if (l !== document.documentElement.lang) { window.location.reload(); } else { setLanguage(l); }
      };
    });
  };

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', applyEarly, { once: true });
  } else {
    applyEarly();
  }
})();

